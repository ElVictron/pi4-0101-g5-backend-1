-- Schema do Backend 1 (PostgreSQL 16).
-- Fontes: CT9 (livros), CT10 (usuarios), CT11 (emprestimos), 00-convencoes §7, §8 e §11.
-- Cria tudo a partir de um schema `public` vazio. Pode ser reaplicado sem erro
-- (IF NOT EXISTS), mas não altera tabelas que já existem.
--
-- Datas: `timestamp(0) without time zone`, no horário de America/Sao_Paulo.
-- O padrão de `criado_em`/`atualizado_em` converte `now()` para esse horário, então não
-- depende do fuso da sessão; é cortado no segundo (sem arredondar para o segundo seguinte).

CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

-- CT9 · livros
CREATE TABLE IF NOT EXISTS livros (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                text NOT NULL,
    autor                 text NOT NULL,
    isbn                  text NOT NULL,
    quantidade_exemplares integer NOT NULL,
    quantidade_disponivel integer NOT NULL,
    criado_em             timestamp(0) without time zone NOT NULL
        DEFAULT date_trunc('second', now() AT TIME ZONE 'America/Sao_Paulo'),
    CONSTRAINT livros_isbn_unico UNIQUE (isbn),
    CONSTRAINT livros_quantidade_exemplares_minima CHECK (quantidade_exemplares >= 1),
    CONSTRAINT livros_quantidade_disponivel_nao_negativa CHECK (quantidade_disponivel >= 0),
    CONSTRAINT livros_disponivel_ate_exemplares
        CHECK (quantidade_disponivel <= quantidade_exemplares)
);

-- CT10 · usuarios
CREATE TABLE IF NOT EXISTS usuarios (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      text NOT NULL,
    cpf       text NOT NULL,
    contato   text NOT NULL,
    criado_em timestamp(0) without time zone NOT NULL
        DEFAULT date_trunc('second', now() AT TIME ZONE 'America/Sao_Paulo'),
    CONSTRAINT usuarios_cpf_unico UNIQUE (cpf)
);

-- CT11 · emprestimos. `atrasado` não é gravado (D3): é calculado na consulta (CT8).
CREATE TABLE IF NOT EXISTS emprestimos (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            integer NOT NULL,
    livro_id              integer NOT NULL,
    status                text NOT NULL,
    emprestado_em         timestamp(0) without time zone NOT NULL,
    data_limite_devolucao timestamp(0) without time zone NOT NULL,
    devolvido_em          timestamp(0) without time zone,
    CONSTRAINT emprestimos_usuario_existe
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT emprestimos_livro_existe
        FOREIGN KEY (livro_id) REFERENCES livros (id) ON DELETE RESTRICT,
    CONSTRAINT emprestimos_status_valido CHECK (status IN ('ativo', 'devolvido')),
    CONSTRAINT emprestimos_status_coerente_com_devolucao
        CHECK ((status = 'devolvido') = (devolvido_em IS NOT NULL)),
    CONSTRAINT emprestimos_prazo_depois_do_emprestimo
        CHECK (data_limite_devolucao > emprestado_em),
    CONSTRAINT emprestimos_devolucao_depois_do_emprestimo
        CHECK (devolvido_em IS NULL OR devolvido_em >= emprestado_em)
);

-- Consultas por usuário (CT4) e por livro; também evitam varredura ao excluir livro/usuário.
CREATE INDEX IF NOT EXISTS emprestimos_usuario_id_idx ON emprestimos (usuario_id);
CREATE INDEX IF NOT EXISTS emprestimos_livro_id_idx ON emprestimos (livro_id);

-- 00-convencoes §8 e §11 · eventos que o Backend 2 não aceitou, para reenvio (P10)
CREATE TABLE IF NOT EXISTS eventos_pendentes (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload       jsonb NOT NULL,
    tentativas    integer NOT NULL DEFAULT 1,
    ultimo_erro   text,
    criado_em     timestamp(0) without time zone NOT NULL
        DEFAULT date_trunc('second', now() AT TIME ZONE 'America/Sao_Paulo'),
    atualizado_em timestamp(0) without time zone NOT NULL
        DEFAULT date_trunc('second', now() AT TIME ZONE 'America/Sao_Paulo'),
    CONSTRAINT eventos_pendentes_tentativas_minima CHECK (tentativas >= 1)
);
